import { NextResponse } from "next/server";

export async function POST(request: Request) {
  try {
    const { message } = await request.json();
    const query = message || "";

    let response = "";
    const workflowSteps: Array<{
      step: "delegation" | "rag" | "agent_reply" | "synthesis";
      agent: string;
      message: string;
      data?: any;
    }> = [];

    // 1. 室長AIの初期化ステップ
    workflowSteps.push({
      step: "delegation",
      agent: "室長AI",
      message: `ご相談内容「${query.length > 25 ? query.substring(0, 25) + "..." : query}」を分析しました。専門分野ごとの調査を開始します。`,
    });

    // キーワード判定によるエージェントとRAGの割り当て
    if (query.includes("工期") || query.includes("延長") || query.includes("遅延") || query.includes("遅れ")) {
      // 工期延長系のシナリオ
      workflowSteps.push({
        step: "rag",
        agent: "RAG検索",
        message: "ナレッジベースから「契約約款・判例集 (contract_precedents.pdf)」を検索しました。約款第26条（不可抗力による工期延期）に関連する記述が見つかりました。",
      });

      workflowSteps.push({
        step: "agent_reply",
        agent: "法務AI",
        message: "民間建設工事標準請負契約約款第26条に基づき、台風や豪雨などの不可抗力による工期遅延については、発注者への速やかな書面通知（工期延長願）と双方の協議が必要です。また、平成15年最高裁判例によると、過失のない損害負担額は合意に基づき適切に分担すべきとされています。",
      });

      workflowSteps.push({
        step: "agent_reply",
        agent: "技術者AI",
        message: "現場目線では、工期延長を願い出るために「遅延日数算出根拠（クリティカルパスの特定）」「天候データ」「施工体制の再計画案」を作成する必要があります。延長に必要な日数のシミュレーションを支援します。",
      });

      response = `工期延長のご相談について、法務および現場視点から回答をまとめました。

不可抗力（悪天候や震災など）による遅延の場合、契約約款に基づき速やかに発注機関へ「工期延長願」を提出し、協議を行う権利があります。

### 必要な手続き・準備
1. **書面による速やかな通知**: 口頭ではなく、客観的な記録として書面（工期延長願）を提出します。
2. **遅延根拠のデータ化**: 降雨量等の気象データ、及び工程表（クリティカルパス）への影響度を明示します。

---
### 📝 工期延長願の作成サンプル（雛形）

**工期延長願**

令和○年○月○日
発注者　○○様
受注者　○○建設株式会社　代表取締役　○○

下記工事について、不可抗力による事由が発生したため、工期の延長を願い出ます。

記
1. **工事名**: ○○改修工事
2. **延長の事由**: 令和○年○月○日の台風○号の直撃に伴う、現場浸水および土砂流入による施工中断のため（中断期間: ○日間）
3. **延長を求める期間**: 令和○年○月○日まで（○日間延長）
4. **添付資料**: 気象庁気象データ、被災写真、遅延影響工程表

---
⚠️ **注意書き**: 本書面はAIが生成した一般的な雛形です。実際に発注機関に提出する際は、必ず弁護士等の有資格者や社内法務担当のリーガルチェックを受けてください。`;
    } 
    else if (query.includes("仕様書") || query.includes("規格") || query.includes("共通") || query.includes("図面")) {
      // 仕様書・技術仕様系のシナリオ
      workflowSteps.push({
        step: "rag",
        agent: "RAG検索",
        message: "ナレッジベースから「公共建築工事標準仕様書 (spec_r6_arch.pdf)」を検索しました。第1章共通参考事項（施工計画書の提出、適用範囲）の関連条文が見つかりました。",
      });

      workflowSteps.push({
        step: "agent_reply",
        agent: "建築AI",
        message: "公共建築工事標準仕様書（令和6年版）第1.1.2条に基づき、受注者は工事着手前に必ず詳細な『施工計画書』を作成し、監督員の承諾を得なければならないと定められています。仕様書規格に準拠した施工法の記載が必須です。",
      });

      workflowSteps.push({
        step: "agent_reply",
        agent: "技術者AI",
        message: "技術検査での指摘を防ぐため、施工計画書には使用材料の適合証明書、安全管理体制、環境配慮事項を網羅する必要があります。特に改修工事では、既存利用部の保護（養生計画）が重要視されます。",
      });

      response = `公共建築工事標準仕様書に関連するご相談について、建築および現場の技術的視点から整理しました。

仕様書は公共工事における契約図書の一部であり、厳格な準拠が求められます。

### 主なポイント（標準仕様書 第1章）
- **施工計画書の事前承諾**: 工事着手前に監督員へ提出し、承諾を得ることが必須要件です（1.1.2条）。
- **材料確認**: 使用する主材料は、事前に品質証明書類を添えて承認申請を行います。
- **検査体制**: 各工程の段階検査（自主検査および監督員立ち会い検査）のスケジュールをあらかじめ明確にしておく必要があります。

必要に応じて、特定の工種（防水、躯体、内装等）の施工基準データも検索・照合可能です。詳細な工種を指定してご質問ください。`;
    } 
    else if (query.includes("下請") || query.includes("一括") || query.includes("禁止") || query.includes("丸投げ") || query.includes("建設業法")) {
      // 一括下請負（丸投げ）禁止・法務シナリオ
      workflowSteps.push({
        step: "rag",
        agent: "RAG検索",
        message: "ナレッジベースから「建設業法第22条（一括下請負の禁止）および行政処分基準」を検索しました。違反時の指名停止期間などのデータが見つかりました。",
      });

      workflowSteps.push({
        step: "agent_reply",
        agent: "法務AI",
        message: "建設業法第22条により、いかなる方法をもってするかを問わず、受注した建設工事を一括して他人に請け負わせること（丸投げ）、また下請負人としてそれを引き受けることは原則として禁止されています。公共工事においては共同住宅等の特例も適用除外となります。違反した場合は営業停止や指名停止処分などの重い罰則が課されます。",
      });

      workflowSteps.push({
        step: "agent_reply",
        agent: "技術者AI",
        message: "元請会社が『実質的に関与』している必要があります。具体的には、施工計画の作成、工程管理、技術的指導、安全管理の4要素について、自社の元請技術者が常駐して主導権を行使している実績を残す必要があります。単に現場に巡回するだけでは実質的関与と認められません。",
      });

      response = `一括下請負（いわゆる丸投げ）の禁止措置と適切な施工管理について、法務および施工監理技術者の見地から整理しました。

建設業法第22条により、元請契約した工事を一括して下請へ流すことは厳格に禁止されています。

### 「実質的関与」と認められるための元請義務
違反を疑われないためには、元請としての以下の役割を自社で果たしていることを日報や管理記録等で証明できるようにする必要があります：
1. **施工計画の策定**: 自社の技術者が計画書を作成・修正していること。
2. **工程管理**: 全体工程および月間・週間工程を調整・指示していること。
3. **技術的指導**: 下請への施工指示や、品質確認・指導を直接行っていること。
4. **安全管理**: 災害防止協議会の主導、朝礼・安全点検の実施。

これらについて明確な記録を残さずに施工を進めると、行政監査などで『丸投げ』と指摘され、営業停止や指名停止措置を受けるリスクがありますので十分ご注意ください。`;
    } 
    else {
      // デフォルトの応答
      workflowSteps.push({
        step: "rag",
        agent: "RAG検索",
        message: "ナレッジベースのインデックスを横断検索しました。標準仕様書やトラブル判例集を含む全3文書を参照します。",
      });

      workflowSteps.push({
        step: "agent_reply",
        agent: "建築AI",
        message: "一般的な技術基準、建築材料の公共仕様適合性などについて、ご質問に応じていつでも関連ドキュメントを検索できます。",
      });

      workflowSteps.push({
        step: "agent_reply",
        agent: "技術者AI",
        message: "現場施工、工程表の計画、安全書類の作成手順、その他技術上の指導案件に関して実務的な視点から回答を補佐します。",
      });

      workflowSteps.push({
        step: "agent_reply",
        agent: "法務AI",
        message: "入札の契約条項、建設業法（一括下請負禁止、監理技術者の専任義務など）、約款トラブル等の法的な確認案件についてお答えします。",
      });

      response = `こんにちは！建築・公共工事に関する専門AIアシスタント「秘書AI」です。

当アシスタント（秘書AI）では、私（**室長AI**）がご質問の窓口となり、必要に応じて**建築AI**、**技術者AI**、**法務AI**に相談を行い、専門ドキュメント（RAG）を検索して回答をまとめます。

例えば、以下のような内容をご相談いただけます：
- **工期延長の手続きや、天候等による遅延約款の解釈**（法務・技術者AI）
- **公共建築工事標準仕様書に基づく施工計画や材料基準**（建築・技術者AI）
- **建設業法に準拠した一括下請負禁止（丸投げ）の制限基準**（法務AI）

左側の推奨質問を選択するか、下の入力欄からお気軽にご質問、または図面や資料を添付してご相談ください。`;
    }

    // 4. 室長AIの統合ステップ
    workflowSteps.push({
      step: "synthesis",
      agent: "室長AI",
      message: "各専門AIの回答および参照RAG知識を統合し、最終的な回答を作成しました。",
    });

    return NextResponse.json({
      response,
      workflowSteps,
    });
  } catch (error) {
    console.error("AI Secretary API error:", error);
    return NextResponse.json({ error: "Internal Server Error" }, { status: 500 });
  }
}
